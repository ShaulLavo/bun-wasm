// Writes crates/bunwasm-runtime/src/js/zone_names.js: the long zone names ICU (native Bun) prints
// in Date.prototype.toString where FormatJS's English data names the zone differently or not at
// all ("India Standard Time" rather than "GMT+05:30"). QuickJS's toString takes a zone's name
// from the fallback Intl and this table corrects it. Keys are `zone|minutes east of UTC`, for the
// standard and daylight offsets of 2024. Run with native Bun: bun scripts/generate-zone-names.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import vm from "node:vm";

const js = join(resolve(import.meta.dir, ".."), "crates/bunwasm-runtime/src/js");
const zoneSource = readFileSync(join(js, "tz_data.js"), "utf8");
const context = vm.createContext({});
const fallback = vm.runInContext(readFileSync(join(js, "intl.js"), "utf8"), context)({
  native: {},
  require(name: string) {
    if (name !== "tz_data") throw new Error(`Unexpected module ${name}`);
    return vm.runInContext(zoneSource, context)();
  },
});
const zones: string[] = vm.runInNewContext(zoneSource)().zones.map((entry: string) => entry.slice(0, entry.indexOf("|")));

function longName(Format: typeof Intl.DateTimeFormat, zone: string, ms: number): string {
  return new Format("en-US", { timeZone: zone, timeZoneName: "long" }).formatToParts(ms).find(part => part.type === "timeZoneName")!.value;
}

// Minutes east of UTC, from ICU's "GMT-03:00" style offset.
function minutesEast(zone: string, ms: number): number {
  const text = new Intl.DateTimeFormat("en-US", { timeZone: zone, timeZoneName: "longOffset" }).formatToParts(ms).find(part => part.type === "timeZoneName")!.value;
  const match = /^GMT(?:([+-])(\d{2}):(\d{2}))?$/.exec(text);
  if (!match) throw new Error(`Unexpected offset ${text} for ${zone}`);
  return match[1] === undefined ? 0 : (match[1] === "-" ? -1 : 1) * (Number(match[2]) * 60 + Number(match[3]));
}

const names: Record<string, string> = {};
for (const zone of zones) {
  for (const ms of [Date.UTC(2024, 0, 15, 12), Date.UTC(2024, 6, 15, 12)]) {
    let icu: string;
    try {
      icu = longName(Intl.DateTimeFormat, zone, ms);
    } catch {
      continue;
    }
    if (icu !== longName(fallback.DateTimeFormat, zone, ms)) names[`${zone}|${minutesEast(zone, ms)}`] = icu;
  }
}
const banner = `// Generated by scripts/generate-zone-names.ts with Bun ${Bun.version} (ICU ${process.versions.icu}).\n`;
writeFileSync(join(js, "zone_names.js"), `${banner}(function () { return ${JSON.stringify(names)}; })\n`);
console.log(`${Object.keys(names).length} names`);
