// Writes crates/bunwasm-runtime/src/js/zone_names.js: the long zone names ICU (native Bun) prints
// in Date.prototype.toString, for every zone in the runtime's zone data, so QuickJS can print a
// date's zone without loading Intl. Keys are `zone|minutes east of UTC`, for the offsets each
// zone uses in January and July of 2024 and 2026. A name ICU prints as the bare offset
// ("GMT-03:00") is left out: the runtime builds that form itself (bootstrap.js gmtName).
// Run with native Bun: bun scripts/generate-zone-names.ts
import { readFileSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";
import vm from "node:vm";

const js = join(resolve(import.meta.dir, ".."), "crates/bunwasm-runtime/src/js");
const zones: string[] = vm.runInNewContext(readFileSync(join(js, "tz_data.js"), "utf8"))().zones
  .map((entry: string) => entry.slice(0, entry.indexOf("|")));

function zonePart(zone: string, ms: number, timeZoneName: "long" | "longOffset"): string {
  return new Intl.DateTimeFormat("en-US", { timeZone: zone, timeZoneName }).formatToParts(ms).find(part => part.type === "timeZoneName")!.value;
}

// Minutes east of UTC, from ICU's "GMT-03:00" style offset.
function minutesEast(zone: string, ms: number): number {
  const text = zonePart(zone, ms, "longOffset");
  const match = /^GMT(?:([+-])(\d{2}):(\d{2}))?$/.exec(text);
  if (!match) throw new Error(`Unexpected offset ${text} for ${zone}`);
  return match[1] === undefined ? 0 : (match[1] === "-" ? -1 : 1) * (Number(match[2]) * 60 + Number(match[3]));
}

// The name the runtime prints for an offset with no entry; keep in step with bootstrap.js gmtName.
function gmtName(minutes: number): string {
  if (minutes === 0) return "GMT";
  const abs = Math.abs(minutes);
  return `GMT${minutes < 0 ? "-" : "+"}${String(Math.floor(abs / 60)).padStart(2, "0")}:${String(abs % 60).padStart(2, "0")}`;
}

const samples = [2024, 2026].flatMap(year => [Date.UTC(year, 0, 15, 12), Date.UTC(year, 6, 15, 12)]);
const names: string[] = [];
const indexes = new Map<string, number>();
const entries: Record<string, number> = {};
for (const zone of zones) {
  for (const ms of samples) {
    let name: string;
    let minutes: number;
    try {
      name = zonePart(zone, ms, "long");
      minutes = minutesEast(zone, ms);
    } catch {
      continue;
    }
    if (name === gmtName(minutes)) continue;
    if (!indexes.has(name)) indexes.set(name, names.push(name) - 1);
    entries[`${zone}|${minutes}`] = indexes.get(name)!;
  }
}
const banner = `// Generated by scripts/generate-zone-names.ts with Bun ${Bun.version} (ICU ${process.versions.icu}).\n`;
writeFileSync(join(js, "zone_names.js"), `${banner}(function () { return ${JSON.stringify({ names, zones: entries })}; })\n`);
console.log(`${Object.keys(entries).length} entries, ${names.length} names`);
