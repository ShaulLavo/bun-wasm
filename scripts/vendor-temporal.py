#!/usr/bin/env python3
"""Rebuild the pinned Temporal fallback used by Bun's TOML date values."""
from pathlib import Path
import shutil
import subprocess
import tempfile

root = Path(__file__).resolve().parent.parent
source = root / "third_party/temporal"
with tempfile.TemporaryDirectory(prefix="bun-wasm-temporal-", dir="/work/tmp") as scratch:
    work = Path(scratch)
    for name in ("package.json", "bun.lock", "entry.js"):
        if (source / name).exists():
            shutil.copyfile(source / name, work / name)
    install = ["bun", "install", "--ignore-scripts", "--linker", "hoisted"]
    if (work / "bun.lock").exists():
        install.append("--frozen-lockfile")
    subprocess.run(install, cwd=work, check=True)
    subprocess.run(["bun", "build", "entry.js", "--target", "browser", "--format", "cjs", "--minify", "--outfile", "bundle.js"], cwd=work, check=True)
    for package, name in (("@js-temporal/polyfill", "LICENSE-temporal"), ("jsbi", "LICENSE-jsbi")):
        shutil.copyfile(work / "node_modules" / package / "LICENSE", source / name)
    shutil.copyfile(work / "bun.lock", source / "bun.lock")
    output = "// Generated by scripts/vendor-temporal.py. Licenses in third_party/temporal.\n"
    output += '(function () { const module = { exports: {} }; const exports = module.exports;\n'
    output += (work / "bundle.js").read_text()
    output += '\nreturn module.exports; })\n'
    (root / "crates/bunwasm-runtime/src/js/temporal.js").write_text(output)
