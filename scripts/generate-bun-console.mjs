import { createRequire } from "node:module";
import { readFileSync, writeFileSync } from "node:fs";
import { execFileSync } from "node:child_process";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const bun = join(root, "vendor/bun");
const ts = createRequire(join(bun, "package.json"))("typescript");
const upstream = "src/js/builtins/ConsoleObject.ts";
const revision = execFileSync("git", ["-C", bun, "log", "-1", "--format=%H", "--", upstream], { encoding: "utf8" }).trim();
const source = readFileSync(join(bun, upstream), "utf8");
const tree = ts.createSourceFile(upstream, source, ts.ScriptTarget.Latest, true);
const declaration = tree.statements.find(node => ts.isFunctionDeclaration(node) && node.name?.text === "createConsoleConstructor");
if (!declaration) throw new Error("Bun Console constructor missing");

function lower(context) {
  const f = context.factory;
  const intrinsic = name => f.createPropertyAccessExpression(f.createIdentifier("intrinsics"), name);
  function visit(node) {
    if (ts.isCallExpression(node) && ts.isPropertyAccessExpression(node.expression) && node.expression.name.text.startsWith("$")) {
      const property = node.expression;
      return f.createCallExpression(intrinsic(property.name.text.slice(1)), undefined,
        [ts.visitNode(property.expression, visit)].concat(Array.from(node.arguments, arg => ts.visitNode(arg, visit))));
    }
    if (ts.isIdentifier(node) && node.text.startsWith("$")) return intrinsic(node.text.slice(1));
    return ts.visitEachChild(node, visit, context);
  }
  return node => ts.visitNode(node, visit);
}
function compile(source) {
  const javascript = ts.transpileModule(source, {
    compilerOptions: { target: ts.ScriptTarget.ESNext, removeComments: true },
  }).outputText;
  const parsed = ts.createSourceFile("console.js", javascript, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  const result = ts.transform(parsed, [lower]);
  const body = ts.createPrinter({ removeComments: true }).printFile(result.transformed[0]);
  result.dispose();
  return body;
}
const timingPath = "src/js/internal/util/debuglog.ts";
const timingSource = readFileSync(join(bun, timingPath), "utf8");
const timingTree = ts.createSourceFile(timingPath, timingSource, ts.ScriptTarget.Latest, true);
const timing = timingTree.statements.filter(node => !ts.isExportAssignment(node)).map(node => node.getText(timingTree)).join("\n");
const timingRevision = execFileSync("git", ["-C", bun, "log", "-1", "--format=%H", "--", timingPath], { encoding: "utf8" }).trim();
const body = compile(declaration.getText(tree).replace(/^export /, ""));
const generated = `// Generated by scripts/generate-bun-console.mjs from Bun ${revision}, ${upstream}.\n// Timing formatter from Bun ${timingRevision}, ${timingPath}.\n// Bun's license is in crates/bunwasm-runtime/generated/builtins/LICENSE.md.\n(function (internal) {\n"use strict";\nconst intrinsics = internal.require("console_constructor");\nconst require = name => name === "internal/util/debuglog" ? { formatTime } : intrinsics.require(name);\n${compile(timing)}\n${body}\nreturn createConsoleConstructor;\n})\n`;
new Function(`return ${generated}`);
const destination = join(root, "crates/bunwasm-runtime/src/js/bun_console_constructor.js");
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== generated) throw new Error("Generated Console differs");
} else writeFileSync(destination, generated);
console.log(`${process.argv.includes("--check") ? "Checked" : "Generated"} Bun Console constructor`);
