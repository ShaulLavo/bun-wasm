#!/usr/bin/env python3
"""Rebuild the pinned WHATWG Streams ponyfill used by the embedded engines."""
from pathlib import Path
import shutil
import subprocess
import tempfile

root = Path(__file__).resolve().parent.parent
source = root / "third_party/streams"
with tempfile.TemporaryDirectory(prefix="bun-wasm-streams-", dir="/work/tmp") as scratch:
    work = Path(scratch)
    for name in ("package.json", "bun.lock", "entry.js"):
        if (source / name).exists():
            shutil.copyfile(source / name, work / name)
    install = ["bun", "install", "--ignore-scripts", "--linker", "hoisted"]
    if (work / "bun.lock").exists():
        install.append("--frozen-lockfile")
    subprocess.run(install, cwd=work, check=True)
    subprocess.run(["node", str(root / "scripts/stream-polyfill-node-hooks.ts"), str(work / "node_modules/web-streams-polyfill/dist/ponyfill.mjs"), str(work / "ponyfill-node.mjs")], check=True)
    (work / "entry.js").write_text('export * from "./ponyfill-node.mjs";\n')
    subprocess.run(["bun", "build", "entry.js", "--target", "browser", "--format", "cjs", "--minify", "--outfile", "bundle.js"], cwd=work, check=True)
    for package, name in (("web-streams-polyfill", "LICENSE"),):
        shutil.copyfile(work / "node_modules" / package / "LICENSE", source / name)
    shutil.copyfile(work / "bun.lock", source / "bun.lock")
    output = "// Generated by scripts/vendor-streams.py. Licenses in third_party/streams.\n"
    output += '(function (internal) { const module = { exports: {} }; const exports = module.exports;\n'
    output += (work / "bundle.js").read_text()
    output += '\nreturn module.exports; })\n'
    (root / "crates/bunwasm-runtime/src/js/streams_polyfill.js").write_text(output)
