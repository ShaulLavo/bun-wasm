#!/usr/bin/env bash
set -euo pipefail
root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
output="${1:-$root/crates/bunwasm-runtime/src/js/ws_builtin.js}"
package="$root/docs/bun-test-suite/dependencies/node_modules/ws"
[[ -f "$package/package.json" ]] || { echo 'Install docs/bun-test-suite/dependencies first.' >&2; exit 1; }
[[ "$(bun -p "require('$package/package.json').version")" == 8.18.3 ]]
scratch="$(mktemp -d /work/tmp/bun-wasm-ws-gen-XXXXXX)"
trap 'rm -rf "$scratch"' EXIT
bun build "$package/index.js" --target=node --format=cjs --external=bufferutil --external=utf-8-validate --outfile="$scratch/ws.cjs" >/dev/null
{
  printf '// Generated by scripts/generate-ws.sh from ws 8.18.3. See docs/bun-patches.md.\n/*!\n'
  cat "$package/LICENSE"
  printf '\n*/\n'
  cat <<'HEADER'
(function (internal) {
  "use strict";
  const module = { exports: {} };
  const require = name => internal.builtin(name.startsWith("node:") ? name : "node:" + name);
HEADER
  cat "$scratch/ws.cjs"
  printf '\n  return module.exports;\n})\n'
} > "$output"
