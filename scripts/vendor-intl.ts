import { chmodSync, copyFileSync, cpSync, mkdirSync, mkdtempSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const source = join(root, "third_party/intl");
const scratch = mkdtempSync(join("/work/tmp", "bun-wasm-intl-"));
const packages = [
  "bigdecimal",
  "fast-memoize",
  "intl-datetimeformat",
  "intl-getcanonicallocales",
  "intl-listformat",
  "intl-locale",
  "intl-localematcher",
  "intl-numberformat",
  "intl-pluralrules",
  "intl-relativetimeformat",
  "intl-segmenter",
  "intl-supportedvaluesof",
];

// The time zone data (FormatJS's add-all-tz payload and its link table) becomes its own module,
// tz_data.js, so the runtime can give QuickJS local time from it without loading the Intl
// bundle (time_zone.ts). The bundle reads the same module, so nothing is duplicated.
function splitZoneData(bundle: string): { bundle: string; zones: string } {
  const call = "Intl.DateTimeFormat.__addTZData(";
  const callStart = bundle.indexOf(call);
  const payloadStart = callStart + call.length;
  const payloadEnd = bundle.indexOf("})", payloadStart) + 1;
  // The link table is the object literal that starts with FormatJS's first link, "-5:00".
  const linksStart = bundle.indexOf('={"-5:00":"EST5EDT"') + 1;
  const linksEnd = bundle.indexOf("}", linksStart) + 1;
  if (callStart < 0 || payloadEnd <= payloadStart || linksStart <= 0 || linksEnd <= linksStart || linksEnd > callStart) {
    throw new Error("FormatJS time zone data moved; update splitZoneData in scripts/vendor-intl.ts");
  }
  const payload = bundle.slice(payloadStart, payloadEnd);
  const links = bundle.slice(linksStart, linksEnd);
  const zones = "// Generated by scripts/vendor-intl.ts from @formatjs/intl-datetimeformat (add-all-tz). Licenses in third_party/intl/licenses.\n"
    + `(function () { "use strict"; const data = ${payload}; data.links = ${links}; return data; })\n`;
  const split = bundle.slice(0, linksStart) + 'internal.require("tz_data").links' + bundle.slice(linksEnd, payloadStart)
    + 'internal.require("tz_data")' + bundle.slice(payloadEnd);
  return { bundle: split, zones };
}

function run(args: string[]): void {
  const result = Bun.spawnSync(args, { cwd: scratch, stdio: ["inherit", "inherit", "inherit"] });
  if (result.exitCode !== 0) throw new Error(`${args.join(" ")} exited with ${result.exitCode}`);
}

try {
  for (const name of ["package.json", "bun.lock", "entry.ts", "namespace.ts", "collator.ts"]) {
    copyFileSync(join(source, name), join(scratch, name));
  }
  run(["bun", "install", "--ignore-scripts", "--linker", "hoisted", "--frozen-lockfile", "--backend", "copy", "--cache-dir", join(scratch, "cache")]);
  cpSync(join(scratch, "node_modules"), join(scratch, "private-node_modules"), { recursive: true, verbatimSymlinks: true });
  rmSync(join(scratch, "node_modules"), { recursive: true });
  renameSync(join(scratch, "private-node_modules"), join(scratch, "node_modules"));
  run(["bun", "build", "entry.ts", "--target", "browser", "--format", "cjs", "--minify", "--outfile", "bundle.js"]);

  const licenses = join(source, "licenses");
  mkdirSync(licenses, { recursive: true });
  for (const name of packages) {
    copyFileSync(join(scratch, "node_modules/@formatjs", name, "LICENSE.md"), join(licenses, `${name}.md`));
    chmodSync(join(licenses, `${name}.md`), 0o644);
  }

  const bundled = readFileSync(join(scratch, "bundle.js"), "utf8").replace(/[ \t]+$/gm, "").trimEnd();
  const { bundle, zones } = splitZoneData(bundled);
  writeFileSync(join(root, "crates/bunwasm-runtime/src/js/tz_data.js"), zones);
  const banner = "// Generated by scripts/vendor-intl.ts. Licenses in third_party/intl/licenses.\n";
  // DateTimeFormat captures Temporal during module initialization. Hide the
  // runtime's lazy getter so Temporal's own date formatting cannot recurse.
  const prefix = "(function (internal) { \"use strict\"; Object.defineProperty(globalThis, \"Intl\", { value: {}, writable: true, configurable: true, enumerable: false }); const temporalDescriptor = Object.getOwnPropertyDescriptor(globalThis, \"Temporal\"); Object.defineProperty(globalThis, \"Temporal\", { value: undefined, writable: true, configurable: true, enumerable: false }); const module = { exports: {} }; const exports = module.exports; try {\n";
  const suffix = "\nreturn module.exports.createIntl(internal); } finally { if (temporalDescriptor) Object.defineProperty(globalThis, \"Temporal\", temporalDescriptor); else delete globalThis.Temporal; } })\n";
  writeFileSync(join(root, "crates/bunwasm-runtime/src/js/intl.js"), banner + prefix + bundle + suffix);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
