import { chmodSync, copyFileSync, mkdirSync, mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { join, resolve } from "node:path";

const root = resolve(import.meta.dir, "..");
const source = join(root, "third_party/intl");
const scratch = mkdtempSync(join("/work/tmp", "bun-wasm-intl-"));
const packages = [
  "bigdecimal",
  "fast-memoize",
  "intl-collator",
  "intl-datetimeformat",
  "intl-getcanonicallocales",
  "intl-listformat",
  "intl-locale",
  "intl-localematcher",
  "intl-numberformat",
  "intl-pluralrules",
  "intl-relativetimeformat",
  "intl-segmenter",
  "intl-supportedvaluesof",
];

function run(args: string[]): void {
  const result = Bun.spawnSync(args, { cwd: scratch, stdio: ["inherit", "inherit", "inherit"] });
  if (result.exitCode !== 0) throw new Error(`${args.join(" ")} exited with ${result.exitCode}`);
}

try {
  for (const name of ["package.json", "bun.lock", "entry.ts", "namespace.ts"]) {
    copyFileSync(join(source, name), join(scratch, name));
  }
  run(["bun", "install", "--ignore-scripts", "--linker", "hoisted", "--frozen-lockfile"]);
  run(["bun", "build", "entry.ts", "--target", "browser", "--format", "cjs", "--minify", "--outfile", "bundle.js"]);

  const licenses = join(source, "licenses");
  mkdirSync(licenses, { recursive: true });
  for (const name of packages) {
    copyFileSync(join(scratch, "node_modules/@formatjs", name, "LICENSE.md"), join(licenses, `${name}.md`));
    chmodSync(join(licenses, `${name}.md`), 0o644);
  }

  const bundle = readFileSync(join(scratch, "bundle.js"), "utf8");
  const banner = "// Generated by scripts/vendor-intl.ts. Licenses in third_party/intl/licenses.\n";
  // DateTimeFormat captures Temporal during module initialization. Hide the
  // runtime's lazy getter so Temporal's own date formatting cannot recurse.
  const prefix = "(function () { \"use strict\"; Object.defineProperty(globalThis, \"Intl\", { value: {}, writable: true, configurable: true, enumerable: false }); const temporalDescriptor = Object.getOwnPropertyDescriptor(globalThis, \"Temporal\"); Object.defineProperty(globalThis, \"Temporal\", { value: undefined, writable: true, configurable: true, enumerable: false }); const module = { exports: {} }; const exports = module.exports; try {\n";
  const suffix = "\nreturn module.exports.intl; } finally { if (temporalDescriptor) Object.defineProperty(globalThis, \"Temporal\", temporalDescriptor); else delete globalThis.Temporal; } })\n";
  writeFileSync(join(root, "crates/bunwasm-runtime/src/js/intl.js"), banner + prefix + bundle + suffix);
} finally {
  rmSync(scratch, { recursive: true, force: true });
}
