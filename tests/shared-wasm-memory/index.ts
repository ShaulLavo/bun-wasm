import { strict as assert } from 'node:assert';

async function moduleFile(name: string) {
  return new WebAssembly.Module(await Bun.file(`${import.meta.dir}/${name}.wasm`).arrayBuffer());
}
function fn(instance: WebAssembly.Instance, name: string): CallableFunction {
  const value = instance.exports[name];
  assert.equal(typeof value, 'function');
  if (typeof value !== 'function') throw new Error(`Missing ${name}`);
  return value;
}

